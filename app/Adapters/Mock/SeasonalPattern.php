<?php

namespace App\Adapters\Mock;

/**
 * Расширяемый механизм сезонности спроса. Каждая реализация — один
 * задокументированный паттерн; MockAdapter применяет произведение
 * множителей всех паттернов, зарегистрированных в конструкторе. Чтобы
 * добавить второй паттерн позже, достаточно реализовать интерфейс и
 * добавить экземпляр в список — без переписывания generate*-методов.
 */
interface SeasonalPattern
{
    /**
     * @param  int  $month  номер месяца, 1-12
     * @return float множитель к базовому спросу для этого месяца
     */
    public function multiplierForMonth(int $month): float;
}
