<?php

namespace App\Core\Domain\Enums;

/**
 * Насколько сделки источника несут продавца. Full — источник ведёт
 * продавца в сделках; отдельные сделки без продавца допустимы (например
 * онлайн-продажи — в моке ~7%), пометки о покрытии нет. Partial — продавец
 * указан только у части сделок; на дашборде показывается доля покрытия.
 * None — ни у одной сделки нет продавца, блок продавцов не показывается.
 * По данным Full и Partial не различить — это заявление источника.
 */
enum SellerCoverage: string
{
    case Full = 'full';
    case Partial = 'partial';
    case None = 'none';
}
